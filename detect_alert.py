"""
detect_alert.py
===============
Real-time fall detection from a webcam or video file using a trained YOLOv8 model.

Designed for hospital CCTV monitoring:
  - Detects falls on stairs, from chairs, from beds, etc.
  - Triggers an audio alarm (alarm.wav) when a fall is confirmed
  - Saves a timestamped screenshot to the alerts/ folder for nurse review
  - Displays live FPS and alarm status on the video feed

Usage:
    python scripts/detect_alert.py

Press 'q' to quit.

Note:
    Run 'python scripts/generate_alarm.py' first to create alarm.wav
"""

import os
import time
import threading
from collections import deque

import cv2
from ultralytics import YOLO

try:
    import winsound   # Windows audio playback
except ImportError:
    winsound = None   # Non-Windows fallback

# =================== SETTINGS ===================
ROOT      = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SOURCE    = 0           # 0 = default webcam  |  or use a video path e.g. "videos/fall_0001.mp4"
WEIGHTS   = os.path.join(ROOT, "runs", "detect", "fall_detector", "weights", "best.pt")
ALARM_WAV = os.path.join(ROOT, "alarm.wav")   # Generated by generate_alarm.py
CONF      = 0.50        # Minimum confidence threshold for detections (0.0 – 1.0)
WINDOW    = 10          # Sliding window size: number of recent frames to consider
MIN_HITS  = 6           # Minimum fall-frames within the window to trigger alarm
COOLDOWN  = 5           # Seconds to wait between consecutive alarms (avoids repeated alerts)
# ================================================

# ---- Verify model weights ----
if not os.path.exists(WEIGHTS):
    raise SystemExit(
        f"[ERROR] Model weights not found: {WEIGHTS}\n"
        f"        Please run 'python scripts/train.py' first."
    )

# ---- Load model ----
model = YOLO(WEIGHTS)
print(f"[INFO] Model loaded. Classes: {model.names}")

# ---- Open video source ----
cap = cv2.VideoCapture(SOURCE)
if not cap.isOpened():
    raise SystemExit(f"[ERROR] Cannot open video source: {SOURCE}")

# ---- Prepare alerts directory ----
alerts_dir = os.path.join(ROOT, "alerts")
os.makedirs(alerts_dir, exist_ok=True)

# ---- Runtime state ----
history    = deque(maxlen=WINDOW)   # Sliding window of bool: True = fall detected in frame
last_alarm = 0.0                    # Timestamp of last alarm
prev_time  = time.time()            # Used for FPS calculation


def play_alarm():
    """Play alarm.wav in a background thread (non-blocking)."""
    if winsound and os.path.exists(ALARM_WAV):
        # Play WAV file (SND_FILENAME = load from file, SND_ASYNC = non-blocking)
        winsound.PlaySound(ALARM_WAV, winsound.SND_FILENAME | winsound.SND_ASYNC)
    elif winsound:
        # Fallback: simple beep if WAV not found
        winsound.Beep(2000, 1500)
    else:
        print("\a", end="", flush=True)   # Terminal bell on Linux/macOS


print("[INFO] Fall Detection System started.")
print(f"[INFO] Monitoring source: {SOURCE}")
print("[INFO] Press 'q' to quit.")
print()

# =================== MAIN LOOP ===================
while True:
    ok, frame = cap.read()
    if not ok:
        print("[INFO] Video stream ended or no frame received.")
        break

    # ---- Run YOLOv8 inference ----
    result = model.predict(frame, conf=CONF, verbose=False)[0]

    # ---- Check for any fall class in detections ----
    detected_falls = [
        model.names[int(cls)]
        for cls in result.boxes.cls
        if "fall" in model.names[int(cls)].lower()
    ]
    history.append(bool(detected_falls))

    # ---- Draw bounding boxes and labels ----
    annotated = result.plot()

    # ---- Overlay FPS counter ----
    now = time.time()
    fps = 1.0 / max(now - prev_time, 1e-6)
    prev_time = now
    cv2.putText(annotated, f"FPS: {fps:.1f}", (10, 30),
                cv2.FONT_HERSHEY_SIMPLEX, 0.75, (0, 255, 0), 2)

    # ---- Overlay monitoring status ----
    status_color = (0, 255, 0)  # Green = normal
    status_text  = "STATUS: NORMAL"
    if sum(history) >= MIN_HITS:
        status_color = (0, 0, 255)   # Red = FALL DETECTED
        fall_type    = detected_falls[0].upper() if detected_falls else "FALL"
        status_text  = f"ALARM: {fall_type} DETECTED!"

        cv2.putText(annotated, status_text, (20, 80),
                    cv2.FONT_HERSHEY_SIMPLEX, 1.2, status_color, 3)

        # ---- Trigger alarm (with cooldown) ----
        if now - last_alarm > COOLDOWN:
            last_alarm = now

            # Save alert screenshot
            alert_path = os.path.join(alerts_dir, f"fall_{int(now)}.jpg")
            cv2.imwrite(alert_path, annotated)
            print(f"[ALARM] {fall_type} detected! Screenshot saved: {alert_path}")

            # Play audio alarm in a background thread (does not freeze the video)
            threading.Thread(target=play_alarm, daemon=True).start()
    else:
        cv2.putText(annotated, status_text, (10, 60),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.75, status_color, 2)

    # ---- Display the annotated frame ----
    display = cv2.resize(annotated, None, fx=0.75, fy=0.75)
    cv2.imshow("Hospital Fall Detection System", display)

    if cv2.waitKey(1) & 0xFF == ord("q"):
        print("[INFO] Quit signal received.")
        break

# ---- Cleanup ----
cap.release()
cv2.destroyAllWindows()
print("[INFO] Fall Detection System stopped.")